"""Signals that a submission may be AI-generated.

Nothing here is proof. Heuristics and the LLM opinion are indicators that
a teacher should follow up on, never an automatic verdict.
"""
from __future__ import annotations

import re
import statistics

from . import llm

MIN_WORDS = 80

AI_PHRASES = [
    "as an ai", "as a language model", "i hope this helps", "certainly!", "great question",
    "delve", "it's important to note", "it is important to note", "it's worth noting",
    "in conclusion", "in summary", "furthermore", "moreover", "additionally",
    "tapestry", "multifaceted", "navigate the complexities", "pivotal", "seamlessly",
    "a testament to", "plays a crucial role", "in today's fast-paced", "foster",
    "embark", "realm", "underscore", "here's a breakdown", "let's break it down",
]

_SENT = re.compile(r"(?<=[.!?])\s+")
_WORD = re.compile(r"[A-Za-zÀ-ỹ']+")


def heuristics(text: str) -> dict:
    words = _WORD.findall(text)
    if len(words) < MIN_WORDS:
        return {"score": None, "signals": [f"Too short to judge ({len(words)} words)."],
                "words": len(words)}

    lower = text.lower()
    signals, score = [], 0.0

    hits = sorted({p for p in AI_PHRASES if p in lower})
    if hits:
        score += min(40, 8 * len(hits))
        signals.append("Typical AI phrasing: " + ", ".join(f'"{h}"' for h in hits[:8]))

    sentences = [s for s in _SENT.split(text.strip()) if len(_WORD.findall(s)) >= 3]
    if len(sentences) >= 5:
        lengths = [len(_WORD.findall(s)) for s in sentences]
        mean = statistics.mean(lengths)
        cv = statistics.pstdev(lengths) / mean if mean else 0
        if cv < 0.35:
            score += 25
            signals.append(f"Very uniform sentence lengths (variation {cv:.2f}; human writing is usually > 0.45).")

    markdown = len(re.findall(r"^\s*(?:#{1,6}\s|\*\*|[-*•]\s|\d+\.\s)", text, re.MULTILINE))
    if markdown >= 5:
        score += 15
        signals.append(f"Heavy list/heading formatting ({markdown} lines), typical of chatbot output.")

    if "—" in text and text.count("—") / max(1, len(words)) > 0.005:
        score += 10
        signals.append("Frequent em-dashes (—).")

    typos = len(re.findall(r"\b(i)\b|\s,|\s{2,}\w|\.\.(?!\.)", text))
    if typos == 0 and len(words) > 200:
        score += 10
        signals.append("No casual errors at all in a long text.")

    return {"score": min(100, round(score)), "signals": signals or ["No strong signals."],
            "words": len(words)}


SYSTEM = (
    "You are helping a teacher review student work. Estimate how likely it is that the "
    "text was generated by an AI assistant rather than written by a student. Consider: "
    "generic, polished but shallow content; stock phrases; uniform structure; lack of "
    "personal voice or mistakes; content that ignores the specific assignment. "
    "Be careful: good students also write well, and false accusations are harmful. "
    'Reply with JSON only: {"likelihood": <0-100>, "reasons": ["short reason", ...]}'
)


def llm_opinion(text: str, assignment: str = "") -> dict:
    data, trimmed = llm.pack_json(SYSTEM, [("Assignment", assignment),
                                           ("Student text", text)])
    try:
        likelihood = max(0, min(100, int(float(data.get("likelihood", 0)))))
    except (TypeError, ValueError):
        likelihood = None
    reasons = data.get("reasons") or []
    if isinstance(reasons, str):
        reasons = [reasons]
    return {"likelihood": likelihood, "reasons": [str(r) for r in reasons][:6],
            "truncated": trimmed}


def check(text: str, assignment: str = "", use_llm: bool = True) -> dict:
    result = {"heuristic": heuristics(text), "llm": None, "error": None}
    if use_llm and result["heuristic"]["score"] is not None:
        try:
            result["llm"] = llm_opinion(text, assignment)
        except llm.LLMError as e:
            result["error"] = str(e)
    return result
